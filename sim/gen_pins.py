"""Generates bridge/pins_gen.h from the pinout tables of the Tiny Tapeout yaml files.

usage: python3 gen_pins.py [-o OUT] [--root DIR]

info.yaml describes the UART test top: one mode (UART), " / " and " or " separate
alternative names of one pin. info_chip.yaml describes the full chip: " / "
separates the load-mode name (rst_n low) from the run-mode name, " or "
separates alternatives inside a mode. A name in parentheses is a note;
"(open drain)" marks an open-drain pad. Empty and "unused" names are skipped.
"""
import argparse
import os
import re
import sys

import yaml

SOURCES = [("info.yaml", ["UART"], True), ("info_chip.yaml", ["LOAD", "RUN"], False)]
BUS = {"ui": "PIN_UI", "uo": "PIN_UO", "uio": "PIN_UIO"}


def c_name(s):
    s = re.sub(r"\(.*?\)", "", s).strip()
    return re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").upper()


def pins_of(path, modes, slash_is_alt):
    with open(path) as fh:
        table = yaml.safe_load(fh).get("pinout") or {}
    out = []
    for key, text in table.items():
        m = re.fullmatch(r"(ui|uo|uio)\[([0-7])\]", key)
        if not m or not text:
            continue
        od = "open drain" in text
        fields = [text] if slash_is_alt else [f.strip() for f in text.split(" / ")]
        if len(fields) != len(modes):
            raise SystemExit("%s: %s: want %d modes, got %r" % (path, key, len(modes), text))
        for mode, field in zip(modes, fields):
            for alt in re.split(r" or | / ", field):
                name = c_name(alt)
                if name and name != "UNUSED":
                    out.append((mode, name, m.group(1), int(m.group(2)), od))
    return out


def render(pins):
    seen = set()
    for mode, name, _, _, _ in pins:
        if (mode, name) in seen:
            raise SystemExit("duplicate pin name %s_%s" % (mode, name))
        seen.add((mode, name))
    w = max(len("PIN_%s_%s" % (m, n)) for m, n, _, _, _ in pins)
    lines = [
        "#ifndef TSE_PINS_GEN_H",
        "#define TSE_PINS_GEN_H",
        "",
        "// Generated by sim/gen_pins.py from the pinout tables of info.yaml",
        "// (mode UART) and info_chip.yaml (modes LOAD and RUN). Do not edit.",
        "",
        '#include "adapter.h"',
        "",
        "typedef struct PinName {",
        "    const char* mode;",
        "    const char* name;",
        "    PinRef      ref;",
        "    uint8_t     open_drain;",
        "} PinName;",
        "",
    ]
    for mode, name, bus, bit, _ in pins:
        lines.append("static const PinRef %-*s = {%s, %d};" % (w, "PIN_%s_%s" % (mode, name), BUS[bus], bit))
    lines += ["", "static const PinName PIN_NAMES[] = {"]
    for mode, name, bus, bit, od in pins:
        lines.append('    {"%s", "%s", {%s, %d}, %d},' % (mode, name, BUS[bus], bit, od))
    lines += ["};", "", "#define PIN_NAMES_N   %d" % len(pins), "", "#endif", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", dest="out", default=os.path.join(os.path.dirname(__file__), "bridge", "pins_gen.h"))
    ap.add_argument("--root", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    a = ap.parse_args()
    pins = []
    for name, modes, alt in SOURCES:
        path = os.path.join(a.root, name)
        if os.path.exists(path):
            pins += pins_of(path, modes, alt)
    if not pins:
        raise SystemExit("no pinout found under %s" % a.root)
    text = render(pins)
    if a.out == "-":
        sys.stdout.write(text)
    else:
        with open(a.out, "w") as fh:
            fh.write(text)


if __name__ == "__main__":
    main()
