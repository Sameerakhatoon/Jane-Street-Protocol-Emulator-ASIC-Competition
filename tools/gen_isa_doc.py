"""Generate docs/isa.md, the instruction-set reference, from isa/tse_isa.yaml
and isa/tse_regs.yaml. The tables are the single source of truth; this page is
regenerated by `make isa-gen` and `make isa-check` fails when it drifts.

usage: gen_isa_doc.py isa/tse_isa.yaml isa/tse_regs.yaml docs/isa.md
"""
import sys

import yaml


def bits(b):
    hi, lo = b
    return f"[{hi}]" if hi == lo else f"[{hi}:{lo}]"


def cycles_text(c):
    parts = ["1 cycle"]
    if "delay" in c:
        parts.append(f"plus `{c['delay']}` delay cycles")
    if c.get("wait") is True:
        parts.append("plus the stall until the condition holds")
    elif "wait" in c:
        parts.append(f"plus a stall when `{c['wait']}` is set")
    if "cfgword" in c:
        parts.append(f"plus {c['cfgword']} when the register is a configuration word (class L)")
    if "dslot" in c:
        nxt = "s + 1" if c["dslot"] == "store" else "s + 2"
        parts.append(f"retires at dispatch; the next instruction waits for the lane's data slot s and runs at {nxt}")
    return ", ".join(parts)


def field_note(f, enums):
    notes = []
    if "enum" in f:
        e = enums[f["enum"]]
        notes.append(", ".join(f"{k}={v}" for k, v in e.items()))
    if f.get("enum_by"):
        notes.append(f"event name, by `{f['enum_by']}` (see the event table)")
    if f.get("kind") == "minus1":
        notes.append("encoded as the written value minus 1")
    if f.get("kind") == "addr":
        notes.append("jump target (label)")
    if f.get("kind") == "csr":
        notes.append("lane register address (see the lane registers)")
    if "flag" in f:
        notes.append(f"keyword `{f['flag']}`")
    if "key" in f:
        notes.append(f"written `{f['key']}=n`")
    if "set_by" in f:
        notes.append(f"set when `{f['set_by']}=` is given")
    if "token" in f:
        notes.append(f"operand `{f['token']}`")
    if "asm_max" in f:
        notes.append(f"assembler accepts up to {f['asm_max']:#x}")
    if "doc" in f:
        notes.append(str(f["doc"]))
    return "; ".join(notes)


def reg_fields(fields):
    out = []
    for name, f in (fields or {}).items():
        if isinstance(f, list):
            out.append(f"{name}{bits(f)}")
        else:
            s = f"{name}{bits(f['bits'])}"
            if "enum" in f:
                s += " (" + ", ".join(f"{k}={v}" for k, v in f["enum"].items()) + ")"
            out.append(s)
    return ", ".join(out)


def main(argv):
    if len(argv) != 4:
        sys.exit(__doc__)
    isa = yaml.safe_load(open(argv[1]))
    regs = yaml.safe_load(open(argv[2]))
    enums = isa["enums"]
    w = isa["word_bits"]
    L = []
    a = L.append
    a("<!-- Generated by tools/gen_isa_doc.py from isa/tse_isa.yaml and isa/tse_regs.yaml. Do not edit; run `make isa-gen`. -->")
    a("")
    a("# TSE instruction set and register map")
    a("")
    a(f"ISA version {isa['version']}. A lane runs {w}-bit instructions. Every instruction takes one cycle to dispatch, plus the "
      "delay, stall or slot wait listed for it, so a program's timing is exact to the cycle; the compiler and the assembler's "
      "timing API use the same numbers. This page is generated from `isa/tse_isa.yaml` and `isa/tse_regs.yaml`, which also "
      "generate the SystemVerilog packages and the assembler tables.")
    a("")
    a("## Machine model")
    a("")
    a("| Item | Value |")
    a("|---|---|")
    a(f"| Instruction word | {w} bits; op in bits [15:13], side-set value in [12:11] |")
    a(f"| Program memory | each lane reads a window of 128 SRAM words (two instructions per word, 256 instructions, 8-bit PC) |")
    a(f"| Fetch slots | lane k owns the SRAM in cycles with cycle mod {isa['frame_slots']} == k |")
    a(f"| Fetch buffer | {isa['fetch_entries']} words per lane, least recently used replaced; fetch latency {isa['fetch_latency']} |")
    a(f"| Data slots | lane k owns data-window cycles with cycle mod {isa['data_frame']} == 4k + 3 |")
    a("| Registers | X, Y (16 bits), T (timeout counter), ISR and OSR (32-bit shift registers), clock C, PC |")
    a("")
    a("Pipeline latencies (measured at the pins by `test/rtl/tb_chip_pins.sv`):")
    a("")
    a("| Constant | Cycles | Meaning |")
    a("|---|---|---|")
    meanings = {
        "instr_to_port": "an instruction dispatched in cycle c changes the output port at edge c + n",
        "port_to_wait": "an input change during cycle k is seen by WAIT in cycle k + n",
        "emit_to_trig_port": "EMIT in cycle c changes the trigger-out port at edge c + n",
        "cfg_write_visible": "CSRW to a configuration word in cycle c is used by the assists from c + n",
        "edge_to_port": "pin-edge response rule: an edge seen in cycle e changes the port at edge e + tick_delay + n",
    }
    for k, v in isa["latency"].items():
        a(f"| `{k}` | {v} | {meanings.get(k, '')} |")
    a("")
    a("## Instructions")
    a("")
    a("| Mnemonic | Match | Cycles | What it does |")
    a("|---|---|---|---|")
    for name, ins in isa["instructions"].items():
        m = ", ".join(f"{k}={v}" for k, v in ins["match"].items())
        a(f"| `{name}` | {m} | {cycles_text(ins['cycles'])} | {ins['doc']} |")
    a("")
    a("### Encodings")
    a("")
    a("Every instruction also carries `op` in bits [15:13] and the side-set value in bits [12:11]. "
      "Bits not listed are reserved and must be 0; the decoder halts the lane on a reserved encoding.")
    a("")
    for name, ins in isa["instructions"].items():
        a(f"**{name}** ({', '.join(f'{k}={v}' for k, v in ins['match'].items())})")
        a("")
        a("| Bits | Field | Notes |")
        a("|---|---|---|")
        for fn, f in sorted(ins["fields"].items(), key=lambda kv: -kv[1]["bits"][0]):
            a(f"| {bits(f['bits'])} | `{fn}` | {field_note(f, enums)} |")
        for c in ins.get("constraints", []):
            a(f"| | | constraint: if {c['if']} then {c['then']} |")
        a("")
    a("### Operand names")
    a("")
    a("| Enumeration | Values |")
    a("|---|---|")
    for en, vals in enums.items():
        a(f"| `{en}` | {', '.join(f'{k}={v}' for k, v in vals.items())} |")
    a("")
    a("### WAIT and STATUS event indices")
    a("")
    a("For `src` PIN, idx 0 to 3 are pin levels and 4 to 7 mean \"pin idx - 4 changed since the WAIT dispatched\".")
    a("")
    a("| Source | Names |")
    a("|---|---|")
    for src, vals in isa["wait_idx"].items():
        a(f"| `{src}` | {', '.join(f'{k}={v}' for k, v in vals.items())} |")
    a("")
    a("## Register map")
    a("")
    a("Classes: **L** configuration word (latch, cleared by the loader, not by reset; a lane's CSRW takes 3 cycles; "
      "programs cannot read it), **F** runtime flop (reset by rst_n), **P** write-only command pulse, **R** read-only.")
    a("")
    a("### Host address regions")
    a("")
    a("| Region | Base | Size | Contents |")
    a("|---|---|---|---|")
    for rn, r in regs["regions"].items():
        a(f"| {rn} | {r['base']:#06x} | {r['size']:#06x} | {r['doc']} |")
    lw = regs["lane_window"]
    a("")
    a(f"### Lane registers (CSRW and CSRR address; host address {lw['host_base']:#06x} + {lw['stride']:#x} x lane + address)")
    a("")
    a("| Address | Name | Class | Fields | Meaning |")
    a("|---|---|---|---|---|")
    for rn, r in regs["lane_regs"].items():
        a(f"| {r['addr']:#04x} | `{rn}` | {r['class']} | {reg_fields(r.get('fields'))} | {r.get('doc', '')} |")
    a("")
    a("### Chip registers (host only)")
    a("")
    a("| Address | Name | Class | Fields | Meaning |")
    a("|---|---|---|---|---|")
    for rn, r in regs["chip_regs"].items():
        addr = f"{r['addr']:#06x}"
        if r.get("count"):
            addr += f" (x{r['count']})"
        a(f"| {addr} | `{rn}` | {r['class']} | {reg_fields(r.get('fields'))} | {r.get('doc', '')} |")
    a("")
    text = "\n".join(L)
    for bad in (chr(0x2013), chr(0x2014)):
        if bad in text:
            sys.exit("gen_isa_doc: an em or en dash in the generated text")
    with open(argv[3], "w") as fh:
        fh.write(text)


if __name__ == "__main__":
    main(sys.argv)
