"""Stage 7, proof generation: a SymbiYosys harness per compiled role.

Every OB-WIN obligation becomes one tse_window_check instance with
LO = ceil(a - d_min) + 1 and HI = floor(b - d_max) formal steps,
and QUIET from the earliest legal next trigger. The top module binds the
program hex to the lane RTL through the placeholder `tse_lane`; the harness
runs once the lane RTL module exists. Until then
`make tsec-proof` runs the checker's own regression (proofs/demo).
"""
import math
import os
import shutil

from .units import lower_bound, upper_bound

TEMPLATES = os.path.join(os.path.dirname(__file__), "proofs", "templates")


def window_bounds(lo, hi, d_min=0, d_max=0):
    """Formal step bounds for a window [lo, hi] in ticks at the pins."""
    return lower_bound(lo - d_min) + 1, upper_bound(hi - d_max)


def harness(role, lane, low, d_min=0, d_max=0):
    """(top module text, [(obligation, LO, HI)]) for one role."""
    f = low.frame
    quiet = math.floor(f.actions[-1].ideals[-1] + f.tail_limit)
    wins = [ob for ob in f.actions if ob.code == "OB-WIN"]
    rows = [(ob, *window_bounds(ob.window[0], ob.window[1], d_min, d_max)) for ob in wins]
    pins = [u.text for u in role.uses]
    lines = [
        f"// top_{role.name.text}.sv: generated by tsec, do not edit.",
        f"// Role {role.name.text} on lane {lane}; one checker per OB-WIN obligation.",
        "module top (input logic clk, input logic [3:0] pin_in);",
        "  logic init = 1'b1;",
        "  always_ff @(posedge clk) init <= 1'b0;",
        "  logic [3:0] pin_out;",
        "  logic sample_strobe;",
        f'  tse_lane #(.PROG_HEX("{role.name.text}.hex"), .LANE({lane})) dut (',
        "    .clk, .rst(init), .pin_in, .pin_out, .sample_strobe);",
    ]
    for k, (ob, lo, hi) in enumerate(rows):
        a = ob.stmt.timing.window.after
        trig = pins.index(a.name.text)
        val = "1'b0" if a.kind == "fall" else "1'b1"
        resp = "sample_strobe" if ob.kind == "in" else f"pin_out[{pins.index(ob.stmt.wire.text)}]"
        lines += [
            f"  // line {ob.line}: {ob.name} within [{float(ob.window[0]):.1f}, "
            f"{float(ob.window[1]):.1f}] ticks after {a.kind}({a.name.text})",
            f"  tse_window_check #(.LO({lo}), .HI({hi}), .QUIET({quiet}), .W(16)) ob{k} (",
            f"    .clk, .rst(init), .trig_in(pin_in[{trig}]), .trig_val({val}),",
            f"    .resp_out({resp}), .resp_val(1'b1));",
        ]
    lines.append("endmodule")
    return "\n".join(lines) + "\n", rows


def sby_text(role_name):
    return "\n".join([
        "[tasks]", "prove prv", "cover cvr", "",
        "[options]", "prv: mode prove", "cvr: mode cover", "cvr: depth 40", "",
        "[engines]", "prv: abc pdr", "cvr: smtbmc boolector", "",
        "[script]", f"read_verilog -formal -sv tse_window_check.sv tse_lane.sv top_{role_name}.sv",
        "prep -top top", "",
        "[files]", "tse_window_check.sv", "tse_lane.sv", f"top_{role_name}.sv", f"{role_name}.hex",
    ]) + "\n"


def write(outdir, role, lane, low, words):
    os.makedirs(outdir, exist_ok=True)
    shutil.copy(os.path.join(TEMPLATES, "tse_window_check.sv"), outdir)
    top, rows = harness(role, lane, low)
    name = role.name.text
    with open(os.path.join(outdir, f"top_{name}.sv"), "w") as fh:
        fh.write(top)
    with open(os.path.join(outdir, f"{name}.sby"), "w") as fh:
        fh.write(sby_text(name))
    with open(os.path.join(outdir, f"{name}.hex"), "w") as fh:
        fh.write("".join(f"{w:04x}\n" for w in words))
    return rows
