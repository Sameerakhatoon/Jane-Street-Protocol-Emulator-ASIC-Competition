"""Export the ISA and register tables into the two portable modules the host side needs.

    python3 host/gen_tables.py

writes host/tse_host/regs_map.py (register addresses and fields for the
loader model, the SPI client and the board) and host/tse_rp2/tse_asm_table.py
(the opcode table of the on-board assembler). Both are plain dicts, no
imports, so they load on MicroPython where tools.tseasm cannot (it uses
dataclasses, typing and re). Run from the repository root.
"""
import os
import pprint
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from tools.tseasm import isa, regs  # noqa: E402

HEAD = "# generated by host/gen_tables.py from isa/%s, do not edit\n"


def reg_entry(r):
    fields = {n: (f["hi"], f["lo"]) for n, f in r["fields"].items()}
    e = {"addr": r["addr"], "class": r["class"], "mask": r["mask"], "fields": fields}
    if r.get("count", 1) > 1:
        e["count"] = r["count"]
        e["stride"] = r["stride"]
    if "host" in r:
        e["host"] = r["host"]
    if "bank" in r:
        e["bank"] = r["bank"]
        e["word"] = r["word"]
    return e


def regs_map():
    out = HEAD % "tse_regs.yaml"
    out += "# Register map of the host bus: CHIP[name] and LANE[name] give addr, class\n"
    out += "# (L config, F flop, P pulse, R read-only), mask and fields {name: (hi, lo)}.\n"
    out += "# A class-L chip register also names its bank (in CHIP_BANKS) and word: the\n"
    out += "# chip keeps one bank of BANK_WORDS x len(CHIP_BANKS) words addressed\n"
    out += "# {bank index, word}.\n"
    tables = [
        ("CHIP", {n: reg_entry(r) for n, r in regs.CHIP.items()}),
        ("LANE", {n: reg_entry(r) for n, r in regs.LANE.items()}),
        ("LANE_WINDOW", dict(regs.LANE_WINDOW)),
        ("REGIONS", {n: {"base": r["base"], "size": r["size"]} for n, r in regs.REGIONS.items()}),
    ]
    for name, t in tables:
        out += "\n%s = %s\n" % (name, pprint.pformat(t, width=100, sort_dicts=True))
    out += "\nCHIP_BANKS = %r\nBANK_WORDS = %d\n\n" % (tuple(regs.CHIP_BANKS), regs.BANK_WORDS)
    for n in ("RUN", "STATUS", "BIST", "LOAD_CRC", "ID", "EV_STATUS", "EV_POP", "TS",
              "MBOX_STATUS", "PIN_OPT"):
        out += "%s = 0x%04X\n" % (n, regs.CHIP[n]["addr"])
    return out


def instr_entry(t):
    keep = ("kind", "enum", "enum_by", "flag", "key", "set_by", "token", "asm_max")
    fields = {}
    for n, f in t["fields"].items():
        e = {"hi": f["hi"], "lo": f["lo"]}
        e.update({k: f[k] for k in keep if k in f})
        fields[n] = e
    # field order is the operand order, so keep it as a list
    return {"value": t["value"], "fields": [(n, fields[n]) for n in t["fields"]],
            "constraints": t["constraints"]}


def asm_table():
    out = HEAD % "tse_isa.yaml and isa/tse_regs.yaml"
    out += "# Opcode table of tse_asm.py. INSTRS[name]: value, fields in operand order\n"
    out += "# [(name, {hi, lo, kind, enum, ...})], constraints. LANE_CSR: lane register\n"
    out += "# name to (addr, class) for CSRW and CSRR operands.\n"
    tables = [
        ("WORD_BITS", isa.WORD_BITS),
        ("SS", tuple(isa.SS)),
        ("ENUMS", isa.ENUMS),
        ("WAIT_IDX", isa.WAIT_IDX),
        ("INSTRS", {n: instr_entry(t) for n, t in isa.INSTRS.items()}),
        ("LANE_CSR", {n: (r["addr"], r["class"]) for n, r in regs.LANE.items()}),
    ]
    for name, t in tables:
        out += "\n%s = %s\n" % (name, pprint.pformat(t, width=100, sort_dicts=False))
    return out


def write(rel, text):
    with open(os.path.join(ROOT, rel), "w", newline="\n") as fh:
        fh.write(text)


def main():
    write("host/tse_host/regs_map.py", regs_map())
    write("host/tse_rp2/tse_asm_table.py", asm_table())
    return 0


if __name__ == "__main__":
    sys.exit(main())
